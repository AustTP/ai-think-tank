def _avatar_sex(name):
    """Best-effort sex guess from an agent's first name, used only to pick the
    avatar's look. Unknown names default to a neutral, generic person rather
    than risking a wrong guess."""
    first = (name or '').strip().split()[0].lower()
    if first in _AVATAR_NAME_SEX['male']:
        return 'male'
    if first in _AVATAR_NAME_SEX['female']:
        return 'female'
    return 'neutral'


def _avatar_description(name, role, is_director=False):
    """Build the PixelLab prompt for one agent's 4-direction sprite. Role picks
    the outfit so workers and directors read differently at a glance."""
    sex = _avatar_sex(name)
    body = {'male': 'a male', 'female': 'a female', 'neutral': 'a person'}[sex]
    if is_director:
        attire = 'dressed in a sharp professional suit and tie'
    else:
        attire = 'wearing a practical worker vest over a plain shirt'
    role_bit = f', filling the role of {role}' if (role or '').strip() else ''
    return (f'{body} office worker named {name or "the agent"}{role_bit}, '
            f'{attire}, friendly face, SNES-style top-down RPG character sprite')


def _pixellab_credits_remaining():
    """Remaining USD credits on the PixelLab account, or None when not
    configured / unreachable (fails closed so avatar generation never runs on
    an unconfigured or unreachable account)."""
    token = _pixellab_token()
    if not token:
        return None
    try:
        req = urllib.request.Request('https://api.pixellab.ai/v2/balance',
                                     headers={'Authorization': f'Bearer {token}'})
        with urllib.request.urlopen(req, timeout=10) as resp:  # nosec B310 -- fixed PixelLab API host
            data = json.loads(resp.read().decode('utf-8', errors='replace'))
        return float((data.get('credits') or {}).get('usd') or 0)
    except Exception:
        return None


def _pixellab_avatar_available():
    remaining = _pixellab_credits_remaining()
    return remaining is not None and remaining > 0


_AVATAR_IN_FLIGHT = set()


def _avatar_dir(agent_id):
    return os.path.join(AGENTS_DIR, agent_id, 'avatars')


def _avatar_set_complete(agent_id):
    d = _avatar_dir(agent_id)
    if not os.path.isdir(d):
        return False
    present = {f for f in os.listdir(d) if f.endswith('.png')}
    return len(present) >= 4


def _ensure_agent_avatar(agent_id, name, role, is_director=False):
    """Generate a 4-direction avatar set for one non-chief-of-staff agent, writing
    AGENTS_DIR/<id>/avatars/. Returns True on success; False when skipped
    (no PixelLab / no credits) or on failure -- the front end falls back to
    the default sprite set either way. Safe to call from a background thread;
    idempotent (skips when the set already exists) and de-duplicated via
    _AVATAR_IN_FLIGHT."""
    if _avatar_set_complete(agent_id):
        return True
    if not _pixellab_avatar_available():
        return False
    if agent_id in _AVATAR_IN_FLIGHT:
        return False
    _AVATAR_IN_FLIGHT.add(agent_id)
    try:
        key = get_or_create_agent_key(agent_id)
        body = {
            'description': _avatar_description(name, role, is_director),
            'image_size': {'width': 48, 'height': 48},
            'view': 'high top-down',
            'template_id': 'mannequin',
        }
        base = _api_base_url('api.pixellab.ai')
        out = _api_execute(agent_id, key, base, 'POST', body, {},
                           'generate per-agent avatar sprite set', workflow=True)
        if out.get('ok') is not True:
            return False
        rotation_urls = (out.get('data') or {}).get('rotation_urls') or {}
        # The job can report completed before /characters/{id} has the final
        # rotation_urls; a single immediate GET used to lose the whole set.
        # Poll the character briefly, then download whatever directions exist.
        char_id = (out.get('ids') or {}).get('character_id')
        if char_id and len([u for u in rotation_urls.values() if u]) < 4:
            for _ in range(12):
                char, _err = _pixellab_call('GET', f'/characters/{char_id}')
                if isinstance(char, dict):
                    rotation_urls = char.get('rotation_urls') or rotation_urls
                if len([u for u in rotation_urls.values() if u]) >= 4:
                    break
                time.sleep(3)
        if not rotation_urls:
            return False
        d = _avatar_dir(agent_id)
        os.makedirs(d, exist_ok=True)
        for direction, url in rotation_urls.items():
            if not url:
                continue
            filename = _avatar_orientation_name(direction) + '.png'
            for attempt in range(3):
                try:
                    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
                    with urllib.request.urlopen(req, timeout=30) as resp:  # nosec B310 -- PixelLab-signed asset URL
                        data = resp.read()
                    with open(os.path.join(d, filename), 'wb') as f:
                        f.write(data)
                    break
                except Exception:
                    if attempt == 2:
                        raise
                    time.sleep(2)
        return _avatar_set_complete(agent_id)
    except Exception:
        return False
    finally:
        _AVATAR_IN_FLIGHT.discard(agent_id)


_AVATAR_LOOP_INTERVAL_S = 30
# Director-driven avatar generation (the old server-side generator is kept
# below for its tests, but is no longer started). The coordinator loop only
# queues a supervisor turn; the director calls generate_agent_avatar, which
# checks PixelLab availability and the budget before spending.
AVATAR_TASK_INTERVAL_S = 30
AVATAR_TASK_BATCH_MAX = 3
AVATAR_TASK_RETRY_COOLDOWN_S = 6 * 3600
AVATAR_GENERATION_MIN_CREDITS_USD = 0.50


def _pixellab_configured():
    """Cheap credential-presence check (no network, no balance call)."""
    try:
        return bool(_pixellab_token())
    except Exception:
        return False


_AVATAR_AVAIL_CACHE = {'at': 0.0, 'ok': False}
AVATAR_AVAILABILITY_TTL_S = 300


def _avatar_generation_available():
    """Cached balance check for the coordinator: the API is usable only when
    the account has at least the policy credit floor. A 5-minute TTL keeps the
    loop from hitting the balance endpoint every 30 seconds."""
    now = time.time()
    cache = _AVATAR_AVAIL_CACHE
    if now - float(cache.get('at') or 0) < AVATAR_AVAILABILITY_TTL_S:
        return bool(cache.get('ok'))
    remaining = _pixellab_credits_remaining()
    cache['at'] = now
    cache['ok'] = (remaining is not None
                   and remaining >= AVATAR_GENERATION_MIN_CREDITS_USD)
    return bool(cache['ok'])


def _avatar_files(agent_id):
    d = _avatar_dir(agent_id)
    if not os.path.isdir(d):
        return []
    return sorted(f for f in os.listdir(d) if f.endswith('.png'))


def generate_agent_avatar(actor_id, target_id, force=False):
    """Director/chief tool: generate one agent's four directional images with
    PixelLab and write them to that agent's own directory
    (AGENTS_DIR/<agent_id>/avatars/). Only a director may target their own team
    (or themselves); the chief may target any non-admin agent. Checks PixelLab
    credentials and a minimum credit balance before spending, and refuses when
    the think tank or the actor's spend cap is exhausted. Idempotent unless
    force=True. Returns a JSON-friendly dict; never raises for a refused call."""
    state = get_state_from_db() or {}
    actor = str(actor_id or '').strip()
    target = str(target_id or '').strip()
    if not actor or not target:
        return {'ok': False, 'error': 'agentId is required'}
    if not _is_director_or_admin(state, actor):
        return {'ok': False, 'error': 'only a director or the chief of staff may generate agent images'}
    roster = {d.get('id'): d for d in (state.get('agentRoster') or [])}
    target_def = roster.get(target)
    if not target_def:
        return {'ok': False, 'error': 'unknown agent'}
    if target_def.get('isAdmin'):
        return {'ok': False, 'error': 'the chief of staff keeps the default sprite'}
    if not _is_admin(state, actor):
        team = supervisor_team_for(state, actor)
        members = set((team or {}).get('members') or [])
        if target != actor and target not in members:
            return {'ok': False, 'error': 'that agent is not on your team'}
    agent = (state.get('agents') or {}).get(target)
    if not agent:
        return {'ok': False, 'error': 'agent state not found'}
    if _avatar_set_complete(target) and not force:
        return {'ok': True, 'agentId': target, 'alreadyComplete': True,
                'dir': _avatar_dir(target), 'files': _avatar_files(target)}
    if target in _AVATAR_IN_FLIGHT:
        return {'ok': False, 'error': 'that agent is already generating'}
    if _think_tank_spend_cap_exceeded():
        return {'ok': False, 'error': 'the think tank spend cap is exhausted'}
    if _agent_spend_cap_exceeded(actor):
        return {'ok': False, 'error': 'your spend cap is exhausted'}
    if _agent_spend_cap_exceeded(target):
        return {'ok': False, 'error': 'that agent\'s spend cap is exhausted'}
    remaining = _pixellab_credits_remaining()
    if remaining is None:
        return {'ok': False, 'error': 'PixelLab is not configured or unreachable'}
    if remaining < AVATAR_GENERATION_MIN_CREDITS_USD:
        return {'ok': False,
                'error': (f'PixelLab has ${remaining:.2f} left; the avatar floor is '
                          f'${AVATAR_GENERATION_MIN_CREDITS_USD:.2f}')}
    ok = _ensure_agent_avatar(target, agent.get('name') or target_def.get('name') or target,
                              agent.get('role') or target_def.get('role') or 'worker',
                              bool(target_def.get('isDirector')))
    files = _avatar_files(target)
    log_action(actor, 'generate_agent_avatar', {
        'agentId': target, 'ok': ok, 'files': files, 'forced': bool(force),
        'remainingBeforeUsd': remaining,
    }, authorized=True)
    if not ok:
        return {'ok': False, 'error': 'PixelLab generation failed; check the service balance'}
    return {'ok': True, 'agentId': target, 'dir': _avatar_dir(target), 'files': files}


def _avatar_task_open(state, agent_id):
    marker = f'({agent_id})'
    for item in (state.get('workQueue') or []):
        title = str(item.get('title') or '')
        if title.startswith('[AVATAR]') and marker in title:
            return True
    for task in (state.get('tasks') or {}).values():
        title = str(task.get('title') or '')
        if (title.startswith('[AVATAR]') and marker in title
                and task.get('status') not in ('done', 'cancelled', 'abandoned', 'failed')):
            return True
    return False


def _avatar_task_team_id(state, target, responsible):
    for team in (state.get('teams') or []):
        if target in (team.get('members') or []):
            return team.get('id')
    for team in (state.get('teams') or []):
        if team.get('directorId') == target:
            return team.get('id')
    for team in (state.get('teams') or []):
        if team.get('directorId') == responsible:
            return team.get('id')
    return responsible


def _queue_avatar_tasks():
    """One coordinator pass: for each non-admin agent with a missing avatar
    set and PixelLab configured, queue one supervisor turn for the responsible
    director. Does not call PixelLab and does not spend generation credits.
    Returns the number of tasks queued."""
    if not _pixellab_configured() or _think_tank_spend_cap_exceeded():
        return 0
    if not _avatar_generation_available():
        return 0
    import sim as _sim
    state = _state_begin()
    try:
        if not state:
            return 0
        if _sim.automation_paused(state):
            return 0
        agents = state.get('agents') or {}
        roster = {d.get('id'): d for d in (state.get('agentRoster') or [])}
        admin = next((d.get('id') for d in (state.get('agentRoster') or [])
                      if d.get('isAdmin')), None)
        now_ms = int(time.time() * 1000)
        seen = state.setdefault('_avatarTaskAt', {})
        queued = 0
        for agent_id, agent in agents.items():
            if roster.get(agent_id, {}).get('isAdmin'):
                continue
            if agent_id in _AVATAR_IN_FLIGHT or _avatar_set_complete(agent_id):
                continue
            if _avatar_task_open(state, agent_id):
                continue
            last = int(seen.get(agent_id) or 0)
            if last and now_ms - last < AVATAR_TASK_RETRY_COOLDOWN_S * 1000:
                continue
            responsible = (roster.get(agent_id, {}).get('director')
                           or (agent_id if roster.get(agent_id, {}).get('isDirector')
                               else admin))
            if not responsible or responsible not in agents:
                continue
            name = agent.get('name') or roster.get(agent_id, {}).get('name') or agent_id
            team_id = _avatar_task_team_id(state, agent_id, responsible)
            _sim.queue_work(state, [{
                'title': f'[AVATAR] Generate four images for {name} ({agent_id})'[:120],
                'room': 'commandcenter',
                'taskType': 'supervise',
                'assignedTo': responsible,
                'teamId': team_id,
                'priority': 'normal',
                'budgetUsd': _sim.SUPERVISOR_CARD_BUDGET_USD,
                'sizeEstimate': 'S',
                'instructions': (
                    f'Generate the four directional character images for {name} '
                    f'({agent_id}) with the generate_agent_avatar tool. The tool writes '
                    f'them to that agent\'s own directory: agents/{agent_id}/avatars/. '
                    'Verify south, north, east, and west all exist. If PixelLab is not '
                    'configured or the budget floor is not met, report that plainly and '
                    'do not retry in this turn. Do not do other work unless the supervisor '
                    'report shows a problem.'
                ),
            }])
            seen[agent_id] = now_ms
            queued += 1
            if queued >= AVATAR_TASK_BATCH_MAX:
                break
        if queued:
            save_state_to_db(state)
        return queued
    finally:
        _state_abort()


async def _avatar_task_loop():
    """Director-driven avatar coordination. The server only queues a turn; the
    director calls PixelLab. This replaces the old server-side generator."""
    while True:
        try:
            await asyncio.to_thread(_queue_avatar_tasks)
        except Exception:
            pass
        await asyncio.sleep(AVATAR_TASK_INTERVAL_S)


async def _avatar_loop():
    """On-hire avatar generation (see the block above). Every pass, look for
    non-chief-of-staff agents that don't yet have a complete avatar set and kick off
    PixelLab generation for them on a background thread. Only runs when the
    PixelLab credential is present AND the account has credits (checked once
    per pass); otherwise it stays idle and the front end keeps the default
    sprite. The on-disk check makes this idempotent and self-healing: a hire
    appears, gets generated; a failed generation is retried next pass."""
    while True:
        try:
            state = get_state_from_db()
            roster = {d.get('id'): d for d in (state.get('agentRoster') or [])}
            agents = state.get('agents') or {}
            if agents and _pixellab_avatar_available():
                for agent_id, a in agents.items():
                    if roster.get(agent_id, {}).get('isAdmin'):
                        continue
                    if agent_id in _AVATAR_IN_FLIGHT or _avatar_set_complete(agent_id):
                        continue
                    threading.Thread(
                        target=_ensure_agent_avatar,
                        args=(agent_id, a.get('name'), a.get('role'),
                              bool(roster.get(agent_id, {}).get('isDirector'))),
                        daemon=True,
                    ).start()
        except Exception:
            pass
        await asyncio.sleep(_AVATAR_LOOP_INTERVAL_S)


# Google Sheets/Calendar: wire up
# the remaining documented-but-unused APIs. Real OAuth refresh_token minted
# live (a real installed-app consent flow, one-time, run by the player --
# this server-side chokepoint only ever holds/refreshes it from here on),
# confirmed working against a real Calendar read before anything was built
# on top of it. Same vault pattern as every other external credential: the
# stored value is a JSON blob {client_id, client_secret, refresh_token}
# (Google OAuth needs all three; every other credential here is a single
# token), and the caller never holds any of it directly.
_GOOGLE_ACCESS_TOKEN_CACHE = {'at': 0.0, 'token': None}
GOOGLE_ACCESS_TOKEN_TTL_S = float(_load_env().get('GOOGLE_ACCESS_TOKEN_TTL_S', '3000') or 3000)  # real tokens last 3599s; refresh a bit early

# Hard per-API rate caps, shared across ALL agents. The whole think tank is ONE
# Google user (one OAuth credential), so Google's per-user quotas apply to the
# entire tank -- this guard keeps every agent together safely UNDER them by
# refusing (fail-closed) when the shared per-minute budget is spent, instead of
# letting the tank drift into a real Google 429. Numbers are deliberately well
# below Google's published per-user limits (Calendar 600 req/min/user, Sheets
# 60 read + 60 write /min/user, Gmail 6,000 quota units/min/user where a
# messages.get already costs 20 units, Docs 300 reads + 60 writes /min/user).
# Each entry: (max_calls_per_minute, min_interval_seconds). The per-minute
# values are operator-tunable via .env (GOOGLE_*_RATE_PER_MIN) so a deployment
# can pace under Google's real published per-user quotas without a code edit;
# the enforcement mechanism below stays in code and the values still fail
# closed (agents can never raise their own ceiling).
_GOOGLE_RATE_LIMITS = {
    'calendar': (float(_load_env().get('GOOGLE_CALENDAR_RATE_PER_MIN', '400') or 400), 0.15),
    'sheets':   (float(_load_env().get('GOOGLE_SHEETS_RATE_PER_MIN', '40') or 40), 0.4),
    'gmail':    (float(_load_env().get('GOOGLE_GMAIL_RATE_PER_MIN', '80') or 80), 0.3),
    'docs':     (float(_load_env().get('GOOGLE_DOCS_RATE_PER_MIN', '80') or 80), 0.3),
}
_GOOGLE_RATE_WINDOW_S = 60.0
_GOOGLE_RATE_LOCK = threading.Lock()
_GOOGLE_RATE_WINDOW: dict[str, list[float]] = {}  # api -> [monotonic call timestamps in the current window]


def _google_api_name(url):
    """Map a Google API URL to its rate-limiter key ('calendar', 'sheets',
    'gmail', 'docs'), or None for hosts the tank does not meter (the OAuth
    token endpoint)."""
    if 'sheets.googleapis.com' in url:
        return 'sheets'
    if 'gmail.googleapis.com' in url:
        return 'gmail'
    if 'docs.googleapis.com' in url:
        return 'docs'
    if 'googleapis.com' in url and '/calendar/' in url:
        return 'calendar'
    return None


def _google_rate_guard(api):
    """Pace + hard-cap Google calls for one API, shared across all agents.
    Returns an error string when the per-minute budget is spent (fail-closed:
    refuse the call rather than risk a real Google 429 -- the caller should
    stop using this API, matching the quota block in the spike prompt). Sleeps
    only the min-interval remainder to smooth bursts, never across the lock.
    Thread-safe via _GOOGLE_RATE_LOCK."""
    max_per_min, min_interval = _GOOGLE_RATE_LIMITS[api]
    now = time.monotonic()
    with _GOOGLE_RATE_LOCK:
        window = [t for t in _GOOGLE_RATE_WINDOW.get(api, [])
                  if now - t < _GOOGLE_RATE_WINDOW_S]
        if len(window) >= max_per_min:
            return (f'Google {api} API rate budget spent this minute '
                    f'({max_per_min} calls/min shared across all agents) -- stop calling this '
                    f'API now; do not retry this investigation.')
        _GOOGLE_RATE_WINDOW[api] = window
        wait = 0.0
        if window:
            wait = min_interval - (now - window[-1])
    if wait > 0:
        time.sleep(wait)
    with _GOOGLE_RATE_LOCK:
        now = time.monotonic()
        window = [t for t in _GOOGLE_RATE_WINDOW.get(api, [])
                  if now - t < _GOOGLE_RATE_WINDOW_S]
        window.append(now)
        _GOOGLE_RATE_WINDOW[api] = window
    return None


def _google_is_configured():
    """True when a usable Google OAuth credential is in the vault (a JSON blob
    with client_id/client_secret/refresh_token). Cheap + non-network: just
    checks the vault entry parses and carries a refresh_token, so callers can
    gate tool availability / prompt text on real configuration without doing a
    token refresh."""
    raw = _open_secret(_credential_token('google') or '')
    if not raw:
        return False
    try:
        creds = json.loads(raw)
    except ValueError:
        return False
    return bool(creds.get('refresh_token'))


def _google_access_token(force=False):
    """Real OAuth access-token refresh (POST https://oauth2.googleapis.com/
    token, grant_type=refresh_token) -- Sheets/Calendar calls need this
    short-lived token, not the long-lived refresh_token directly. Returns
    (token, error). Cached for GOOGLE_ACCESS_TOKEN_TTL_S; `force=True`
    bypasses the cache (same reasoning as PixelLab's balance force-refresh:
    a caller that specifically needs a guaranteed-fresh token, e.g. after a
    401, shouldn't get a stale cached one back)."""
    now = time.time()
    cached = _GOOGLE_ACCESS_TOKEN_CACHE
    if not force and cached['token'] and (now - cached['at']) < GOOGLE_ACCESS_TOKEN_TTL_S:
        return cached['token'], None
    raw = _open_secret(_credential_token('google') or '')
    if not raw:
        return None, 'Google is not configured (no credential in the vault)'
    try:
        creds = json.loads(raw)
    except ValueError:
        return None, 'Google credential is malformed'
    if not creds.get('refresh_token'):
        return None, 'Google is not configured (no refresh_token -- the OAuth consent step was never completed)'
    try:
        data = urllib.parse.urlencode({
            'client_id': creds['client_id'],
            'client_secret': creds['client_secret'],
            'refresh_token': creds['refresh_token'],
            'grant_type': 'refresh_token',
        }).encode()
        req = urllib.request.Request('https://oauth2.googleapis.com/token', data=data, method='POST')
        with urllib.request.urlopen(req, timeout=20) as resp:  # nosec B310 -- fixed Google OAuth host
            tokens = json.loads(resp.read().decode('utf-8', errors='replace'))
        token = tokens.get('access_token')
        if not token:
            return None, f'Google token refresh returned no access_token: {json.dumps(tokens)[:300]}'
        cached['at'] = now
        cached['token'] = token
        return token, None
    except urllib.error.HTTPError as e:
        detail = e.read().decode('utf-8', errors='replace')[:500]
        return None, f'Google token refresh failed ({e.code}): {detail}'
    except Exception as e:
        return None, f'Google token refresh failed: {e}'


def _google_call(method, url, body=None, timeout=30):
    """Real authenticated call to a Google API (Sheets/Calendar), given a
    full URL (both APIs live on different hosts -- sheets.googleapis.com,
    www.googleapis.com/calendar -- so the caller supplies the whole thing,
    unlike Treg/PixelLab's single fixed host). Retries ONCE with a forced
    token refresh on a 401 (an access token can expire mid-session; that's
    not a real failure, just an expected refresh point). Returns
    (data, error), same 2-tuple shape as every other real integration
    """
    api = _google_api_name(url)
    if api:
        rate_error = _google_rate_guard(api)
        if rate_error:
            return None, rate_error
    token, error = _google_access_token()
    if error:
        return None, error
    for attempt in range(2):
        try:
            data_bytes = json.dumps(body).encode('utf-8') if body is not None else None
            req = urllib.request.Request(
                url, data=data_bytes, method=method,
                headers={'Authorization': f'Bearer {token}', 'Content-Type': 'application/json'})
            with urllib.request.urlopen(req, timeout=timeout) as resp:  # nosec B310 -- fixed Google API hosts
                return json.loads(resp.read().decode('utf-8', errors='replace')), None
        except urllib.error.HTTPError as e:
            if e.code == 401 and attempt == 0:
                token, error = _google_access_token(force=True)
                if error:
                    return None, error
                continue
            detail = e.read().decode('utf-8', errors='replace')[:500]
            return None, f'Google call failed ({e.code}): {detail}'
        except Exception as e:
            return None, f'Google call failed: {e}'


def _github_call(method, url, body=None, timeout=30):
    """Real authenticated call to the GitHub REST API (api.github.com), given
    a full URL. Read-only capability: lets the think tank's
    engineering work ground itself in REAL public repos/issues/PRs instead of
    hallucinating plausible-looking ones. The PAT comes from GITHUB_TOKEN in
    .env (classic/fine-grained with read:repo+public read scope). Free --
    GitHub's public API has no per-call spend, only a per-hour rate limit, so
    there's no kv_spend accrual (same as Google Sheets/Calendar). Returns
    (data, error), the same 2-tuple shape as _google_call / _treg_call."""
    token = GITHUB_TOKEN
    if not token:
        return None, 'GitHub is not configured (no GITHUB_TOKEN in .env)'
    try:
        data_bytes = json.dumps(body).encode('utf-8') if body is not None else None
        req = urllib.request.Request(
            url, data=data_bytes, method=method,
            headers={'Authorization': f'Bearer {token}',
                     'Accept': 'application/vnd.github+json',
                     'X-GitHub-Api-Version': '2022-11-28'})
        with urllib.request.urlopen(req, timeout=timeout) as resp:  # nosec B310 -- fixed GitHub API host
            return json.loads(resp.read().decode('utf-8', errors='replace')), None
    except urllib.error.HTTPError as e:
        detail = e.read().decode('utf-8', errors='replace')[:500]
        return None, f'GitHub call failed ({e.code}): {detail}'
    except Exception as e:
        return None, f'GitHub call failed: {e}'


# DigitalOcean is the one external credential
# where a mistake is real, hard-to-reverse money (a created Droplet keeps
# billing even powered off -- see library/skills/digitalocean.md), so it gets
# a HARD circuit breaker here, not just a number a director can choose to
# look at. This checks the REAL account balance from DigitalOcean itself, not
# only the think tank's own kv_spend ledger -- a future integration that forgot
# to call _accrue_spend, or an agent routing around it, would leave the
# internal ledger reading $0 while real money was still being spent. The
# higher of the two numbers wins, and any check failure (network, no
# credential) refuses rather than assuming it's fine.
_HARD_CAPPED_CREDENTIALS = {
    'digitalocean': _digitalocean_account_balance,
    'treg': _treg_account_balance,
    'pixellab': _pixellab_account_balance,
}

# A real capability handle only gets an agent as far as a decrypted secret --
# HOW that secret is attached to the outbound request still differs per
# service. DigitalOcean and PixelLab both take a standard
# `Authorization: Bearer <token>` (confirmed against both APIs); Treg
# does not -- its real API takes `X-Treg-Token: <token>` (see
# _treg_account_balance / library/skills/treg.md), and would silently 401 if
# handed a Bearer header instead.
# real handle-authenticated action: /api/curl's injection line was hardcoded
# to Bearer, which is correct for DO/PixelLab but WRONG for Treg. Anything
# not listed here defaults to Bearer, the common case.
_CREDENTIAL_AUTH_HEADER = {
    'treg': lambda secret: {'X-Treg-Token': secret},
}


def _capability_auth_headers(credential_name, secret):
    """Return the {header: value} to inject for this credential's real API.
    See _CREDENTIAL_AUTH_HEADER above for why this can't just be a hardcoded
    Bearer header everywhere."""
    builder = _CREDENTIAL_AUTH_HEADER.get(credential_name)
    if builder:
        return builder(secret)
    return {'Authorization': f'Bearer {secret}'}


def _credential_over_cap(credential_name, snapshot):
    """Returns (True, reason) if minting a handle for this credential should
    be hard-refused right now, else (False, None). Only credentials in
    _HARD_CAPPED_CREDENTIALS are checked -- everything else is unaffected."""
    real_check = _HARD_CAPPED_CREDENTIALS.get(credential_name)
    if not real_check:
        return False, None
    products = (snapshot.get('products') or {}) if isinstance(snapshot, dict) else {}
    product = products.get(credential_name) if isinstance(products, dict) else None
    cap = product.get('budgetCapUsd') if isinstance(product, dict) else None
    if not isinstance(cap, (int, float)) or cap <= 0:
        return False, None  # no cap configured -- nothing to enforce yet
    real_usage = real_check()
    if real_usage is None:
        return True, (f'{credential_name}: could not verify the real account balance '
                       f'right now -- refusing to grant access rather than assume it is under cap.')
    ledger_usage = float((_spend_ledger_read() or {}).get(credential_name, {}).get('used', 0) or 0)
    usage = max(real_usage, ledger_usage)
    if usage >= cap:
        return True, f'{credential_name}: ${usage:.2f} of ${cap:.2f} cap already used -- refusing to grant more access.'
    return False, None


def mint_capability_handle(agent_id, credential_name, purpose, allowed_hosts,
                           allowed_methods, granted_by, ttl_s):
    """Mint a scoped handle to a stored credential. Returns (handle, None) on
    success -- the opaque handle nonce, shown to the caller ONCE -- or
    (None, reason) on refusal (unknown credential, or a hard-capped
    credential already at/over its budget). The handle is unrelated to the
    credential -- knowing it reveals nothing."""
    with _db() as conn:
        row = conn.execute(
            "SELECT 1 FROM external_credentials WHERE name = ? AND status = 'active'",
            (credential_name,)).fetchone()
        if not row:
            return None, 'unknown credential'
        # Master gate for the DigitalOcean credential: the DO
        # token is only reachable when SANDBOX_EXECUTION=digitalocean. While
        # the switch reads `local` (the default), NO handle for it can even be
        # minted -- an agent can never get a DO handle to try, matching the
        # player's rule that DO is unreachable until the variable is flipped.
        if credential_name == 'digitalocean' and not _digitalocean_enabled():
            reason = ('DigitalOcean is disabled: SANDBOX_EXECUTION=local in .env. '
                      'Set SANDBOX_EXECUTION=digitalocean to enable it.')
            log_action(granted_by, 'handle_mint_refused',
                      {'agentId': agent_id, 'credential': credential_name, 'reason': reason},
                      authorized=True)
            return None, reason
        over_cap, reason = _credential_over_cap(credential_name, get_state_from_db() or {})
        if over_cap:
            log_action(granted_by, 'handle_mint_refused',
                      {'agentId': agent_id, 'credential': credential_name, 'reason': reason},
                      authorized=True)
            return None, reason
        handle = secrets.token_hex(32)
        conn.execute(
            'INSERT INTO capability_handles (handle, agent_id, credential_name, purpose, '
            'allowed_hosts, allowed_methods, granted_by, expires_at, created_at) '
            'VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
            (handle, agent_id, credential_name, purpose,
             json.dumps(allowed_hosts), json.dumps(allowed_methods),
             granted_by, time.time() + ttl_s, time.time()),
        )
        return handle, None


def _revoke_handle(handle):
    with _db() as conn:
        conn.execute('DELETE FROM capability_handles WHERE handle = ?', (handle,))


def revoke_all_handles(agent_id):
    with _db() as conn:
        conn.execute('DELETE FROM capability_handles WHERE agent_id = ?', (agent_id,))


def revoke_agent_credentials(agent_id):
    """Revoke EVERY standing grant a fired agent held, so nothing survives the
    fire: the per-agent attribution secret (agent_keys -- without this a fired
    agent could still sign requests it was never re-authorized for), any
    temporary capability grants, any external-capability handles, and any
    sublow or JEV experiment grants (a live grant token would otherwise keep
    buying inference under the dead agent's name). A later RE-hire mints a
    fresh key on first use (get_or_create_agent_key)."""
    with _db() as conn:
        conn.execute('DELETE FROM agent_keys WHERE agent_id = ?', (agent_id,))
        conn.execute('DELETE FROM temp_access_grants WHERE agent_id = ?', (agent_id,))
        conn.execute('DELETE FROM capability_handles WHERE agent_id = ?', (agent_id,))
    revoke_agent_sublow_grants(agent_id)
    revoke_agent_jev_grants(agent_id)


def _expire_handles(now=None):
    """Drop handles whose expiry has passed. Mirrors how temp_access_grants
    treats a stale row as absent -- here we actually remove it. Cheap enough to
    run inside the cadence pass."""
    with _db() as conn:
        conn.execute('DELETE FROM capability_handles WHERE expires_at <= ?',
                     (time.time() if now is None else now,))


def verify_capability_handle_scope(agent_id, handle, method, url):
    """The scope-check half of resolve_capability_handle: verifies the grant
    exists, is for this agent, is unexpired, and the host+method are in scope.
    Returns the grant row (credential_name, purpose, service) or None. Does NOT
    decrypt the credential -- callers that need the secret call
    resolve_capability_handle after their own policy gate (Jev) has approved
    the action, so a blocked action never touches the vault."""
    if not agent_id or not handle:
        return None
    with _db() as conn:
        row = conn.execute(
            'SELECT credential_name, purpose, allowed_hosts, allowed_methods, expires_at '
            'FROM capability_handles WHERE handle = ? AND agent_id = ?',
            (handle, agent_id)).fetchone()
        if not row:
            return None
        credential_name, purpose, allowed_hosts, allowed_methods, expires_at = row
        # Defense-in-depth on top of the mint gate: a handle
        # minted while SANDBOX_EXECUTION=digitalocean must NOT keep working if
        # the switch is later flipped back to `local`. The mint gate stops new
        # DO handles; this stops a leftover one from resolving, so DO stays
        # unreachable the instant the variable stops saying digitalocean.
        if credential_name == 'digitalocean' and not _digitalocean_enabled():
            return None
        # Handles store their scope as JSON ('["api.github.com"]', '["*"]'); the
        # '*' wildcard is stored as a singleton list. Decode back to real lists
        # so the scope checks below compare actual values, not the raw JSON text.
        try:
            allowed_hosts = json.loads(allowed_hosts) if isinstance(allowed_hosts, str) else allowed_hosts
            allowed_methods = json.loads(allowed_methods) if isinstance(allowed_methods, str) else allowed_methods
        except Exception:
            return None
        if time.time() > expires_at:
            conn.execute('DELETE FROM capability_handles WHERE handle = ?', (handle,))
            return None
        host = urllib.parse.urlparse(url).hostname or ''
        if not host:
            return None
        if allowed_hosts != '*' and host not in (allowed_hosts or []):
            return None
        if method not in (allowed_methods or []):
            return None
        cred_row = conn.execute(
            'SELECT service FROM external_credentials WHERE name = ?',
            (credential_name,)).fetchone()
        if not cred_row:
            return None
        service = cred_row[0]
    return {'credential_name': credential_name, 'purpose': purpose, 'service': service}
